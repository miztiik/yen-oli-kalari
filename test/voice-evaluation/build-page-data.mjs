/**
 * Scan results/ and emit one payload the page can load from a file path.
 *
 * The page has no server and no build step - it is opened by double-clicking
 * it, and a browser reading a `file://` document refuses `fetch` against a
 * sibling JSON file. So everything arrives as a script that assigns a global.
 * Audio elements are not subject to that rule, which is why clips are still
 * referenced by relative path.
 *
 * One run per model and quantisation, nothing overwritten, so the page can put
 * two models beside each other - which is the only way a listening test that
 * means anything can be run. Pairwise preference beats absolute scoring, which
 * is how TTS Arena ranks and why the A/B tab exists.
 *
 * Usage:
 *   npm run build-page
 *   CLIP_BASE=./clips/ CLIP_EXTENSION=.ogg npm run build-page
 */

import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join } from "node:path";
import { summariseRun } from "./metrics.mjs";

const RESULTS_DIR = fileURLToPath(new URL("./results/", import.meta.url));
const CATALOGUE_PATH = fileURLToPath(new URL("./model-catalogue.json", import.meta.url));
const OUTPUT_PATH = fileURLToPath(new URL("./page/data.js", import.meta.url));

/* Where the page looks for audio, and what it is called there. Locally the
   clips stay in results/<model>/<quant>/; the published site flattens and
   encodes them. Both are written into the payload rather than assumed by the
   page, so one page serves both without a build flag. */
const CLIP_BASE = process.env.CLIP_BASE ?? "../results/";
const CLIP_EXTENSION = process.env.CLIP_EXTENSION ?? "";

if (!existsSync(RESULTS_DIR)) {
  console.error("No results/ directory. Run `npm run build-clips` first.");
  process.exit(1);
}

const catalogue = JSON.parse(readFileSync(CATALOGUE_PATH, "utf8"));

function directories(path) {
  return readdirSync(path).filter((name) => statSync(join(path, name)).isDirectory());
}

const runs = [];
for (const modelSlug of directories(RESULTS_DIR)) {
  for (const quantisation of directories(join(RESULTS_DIR, modelSlug))) {
    const manifestPath = join(RESULTS_DIR, modelSlug, quantisation, "manifest.json");
    if (!existsSync(manifestPath)) continue;

    const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
    const missing = manifest.clips.filter(
      (clip) => !existsSync(join(RESULTS_DIR, modelSlug, quantisation, clip.clip)),
    );
    if (missing.length > 0) {
      console.error(`${modelSlug}/${quantisation}: ${missing.length} clip(s) named but not on disk`);
      process.exit(1);
    }

    if (CLIP_EXTENSION) {
      for (const clip of manifest.clips) clip.clip = clip.clip.replace(/\.wav$/, CLIP_EXTENSION);
    }
    manifest.clipBase = `${CLIP_BASE}${modelSlug}/${quantisation}/`;
    /* The metrics a dashboard shows first, computed once here rather than in
       the browser, so the published payload carries the same figures a CI job
       would read. */
    manifest.metrics = summariseRun(manifest);
    manifest.runId = `${modelSlug}/${quantisation}`;
    runs.push(manifest);
  }
}

if (runs.length === 0) {
  console.error("results/ holds no manifest. Run `npm run build-clips` first.");
  process.exit(1);
}

/* Newest first, and the incumbent's own runs before any challenger's, so the
   page opens on the thing most people came to hear. */
runs.sort((a, b) => {
  const incumbent = (run) => (catalogue.models[run.modelSlug]?.incumbent ? 0 : 1);
  return incumbent(a) - incumbent(b) || a.runId.localeCompare(b.runId);
});

const payload = {
  schemaVersion: "2026-09-13",
  generatedAt: new Date().toISOString(),
  catalogue: catalogue.models,
  runs,
};

writeFileSync(
  OUTPUT_PATH,
  `/* Generated by build-page-data.mjs - do not edit. */\nwindow.EVALUATION_DATA = ${JSON.stringify(payload, null, 2)};\n`,
  "utf8",
);

console.log(`wrote page/data.js`);
for (const run of runs) {
  const known = catalogue.models[run.modelSlug];
  console.log(
    `  ${run.runId.padEnd(30)} ${String(run.totals.clipCount).padStart(3)} clips  ` +
      `RTF ${String(run.totals.realTimeFactor).padEnd(7)} ${run.totals.wordsAMinute} wpm  ` +
      `${run.host.isCi ? "runner" : "laptop"}${known ? "" : "  [not in catalogue]"}`,
  );
}
console.log(`clips resolve from ${CLIP_BASE}<model>/<quant>/${CLIP_EXTENSION ? ` as *${CLIP_EXTENSION}` : ""}`);
