/**
 * Write the clip manifest as a script the evaluation page can load from a file
 * path.
 *
 * The page has no server and no build step - it is opened by double-clicking
 * it. A browser reading a `file://` document refuses `fetch` against a sibling
 * JSON file, so the manifest arrives as a script that assigns a global instead.
 * Audio elements are not subject to that rule, which is why the WAVs are still
 * referenced by relative path.
 *
 * Separate from build-evaluation-clips.mjs so the page can be rebuilt without
 * re-synthesising nine minutes of audio.
 *
 * Usage:
 *   npm run build-page
 */

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";

const MANIFEST_PATH = fileURLToPath(new URL("./clips/manifest.json", import.meta.url));
const OUTPUT_PATH = fileURLToPath(new URL("./page/manifest.js", import.meta.url));

if (!existsSync(MANIFEST_PATH)) {
  console.error("No clips/manifest.json found. Run `npm run build-clips` first.");
  process.exit(1);
}

const manifest = JSON.parse(readFileSync(MANIFEST_PATH, "utf8"));

const missing = manifest.clips.filter(
  (clip) => !existsSync(fileURLToPath(new URL(`./clips/${clip.clip}`, import.meta.url))),
);
if (missing.length > 0) {
  console.error(`Manifest names ${missing.length} clip(s) that are not on disk:`);
  for (const clip of missing) console.error(`  ${clip.clip}`);
  process.exit(1);
}

const banner = `/* Generated by build-page-manifest.mjs - do not edit.
   Source: clips/manifest.json, built ${manifest.generatedAt} */\n`;

writeFileSync(OUTPUT_PATH, `${banner}window.EVALUATION_MANIFEST = ${JSON.stringify(manifest, null, 2)};\n`, "utf8");

console.log(`wrote page/manifest.js - ${manifest.clips.length} clips, ${manifest.totals.audioSeconds}s of audio`);
console.log(`open page/index.html to listen`);
