/**
 * Vendor the d3 modules this page uses into one committed file.
 *
 * WHY THIS EXISTS AT ALL. The page must open from a file path with no bundler
 * and no network, so it cannot `import` from `node_modules` and it may not
 * fetch a script from a third party at runtime (`CLAUDE.md` Guardrail #1). The
 * answer is a vendored bundle: built once, committed, read from disk like any
 * other asset. The page still has no build step - this script does, and it runs
 * when a d3 version changes rather than when the page is opened.
 *
 * WHY NOT THE WHOLE OF d3. `d3` is a meta-package of 30 modules and about
 * 280 KB before compression; this page uses nine of them. Importing the meta
 * package would put geographic projections, hierarchies, chord diagrams, force
 * simulations and delaunay triangulation on a listening bench that draws three
 * bar charts and four sliders. Guardrail #8 asks a dependency to name its
 * beneficiary feature and its cost, and the honest way to keep that cost small
 * is to name the modules.
 *
 * The beneficiary features, one module at a time:
 *   d3-selection  - binds data to the score rails and the chart marks
 *   d3-transition - the fill that springs to a chosen score
 *   d3-ease       - the curve that makes it spring rather than slide
 *   d3-scale      - value to pixels, in both the charts and the rails
 *   d3-array      - extents and ticks
 *   d3-shape      - the rounded bar and the progress arc
 *   d3-axis       - the chart axes that were hand-drawn as line elements
 *   d3-drag       - dragging a score handle
 *   d3-format     - one rounding rule for every figure on the page
 *
 * Usage:
 *   npm run vendor-d3
 */

import { build } from "esbuild";
import { fileURLToPath } from "node:url";
import { mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { gzipSync } from "node:zlib";
import { dirname } from "node:path";

const ENTRY = fileURLToPath(new URL("./d3-entry.mjs", import.meta.url));
const OUTPUT = fileURLToPath(new URL("./page/vendor/d3-micro.js", import.meta.url));

mkdirSync(dirname(OUTPUT), { recursive: true });

const versions = JSON.parse(
  readFileSync(fileURLToPath(new URL("./package.json", import.meta.url)), "utf8"),
).devDependencies;

const modules = Object.keys(versions)
  .filter((name) => name.startsWith("d3-"))
  .sort();

await build({
  entryPoints: [ENTRY],
  outfile: OUTPUT,
  bundle: true,
  minify: true,
  format: "iife",
  /* One global, named for what it is. The page reads `window.d3` exactly as it
     would with the full distribution, so nothing on the page knows this is a
     trimmed build. */
  globalName: "d3",
  target: ["es2019"],
  legalComments: "none",
  banner: {
    js:
      `/* d3, trimmed to ${modules.length} modules for the voice-evaluation page. GENERATED by vendor-d3.mjs - do not edit.\n` +
      `   ${modules.map((name) => `${name}@${versions[name]}`).join(", ")}\n` +
      `   Rebuild: npm run vendor-d3. Licence: ISC, (c) Mike Bostock. */`,
  },
});

const bytes = statSync(OUTPUT).size;
const gzipped = gzipSync(readFileSync(OUTPUT)).length;

/* The number is printed rather than assumed, because Guardrail #10 does not
   stop at the runner: a byte cost quoted from memory is an estimate too. */
console.log(
  `wrote page/vendor/d3-micro.js - ${modules.length} modules, ` +
    `${(bytes / 1024).toFixed(1)} KB raw, ${(gzipped / 1024).toFixed(1)} KB gzipped`,
);

writeFileSync(
  fileURLToPath(new URL("./page/vendor/d3-micro.json", import.meta.url)),
  `${JSON.stringify(
    {
      note: "What is in the vendored d3 bundle and what it weighs. Written by vendor-d3.mjs so the figure on the page and in the docs comes from a measurement rather than a memory.",
      builtAt: new Date().toISOString(),
      modules: Object.fromEntries(modules.map((name) => [name, versions[name]])),
      bytes,
      gzippedBytes: gzipped,
    },
    null,
    2,
  )}\n`,
  "utf8",
);
